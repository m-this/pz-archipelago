package main

import (
	"bytes"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"regexp"
	"strconv"
	"strings"
)

const header = "// Code generated by importapworld from the upstream apworld. DO NOT EDIT.\n\npackage gamedata\n\n"

func run(world, target string) error {
	up, err := readUpstream(world)
	if err != nil {
		return err
	}
	files := map[string]func(upstream) (string, error){
		"species_generated.go":   speciesTable,
		"items_generated.go":     itemsTable,
		"locations_generated.go": locationsTable,
	}
	for name, table := range files {
		body, err := table(up)
		if err != nil {
			return fmt.Errorf("%s: %w", name, err)
		}
		formatted, err := format.Source([]byte(header + body))
		if err != nil {
			return fmt.Errorf("%s: %w", name, err)
		}
		if err := os.WriteFile(filepath.Join(target, name), formatted, 0o644); err != nil {
			return err
		}
	}
	return nil
}

func speciesTable(up upstream) (string, error) {
	var b bytes.Buffer
	b.WriteString("var AllSpecies = []Species{\n")
	for _, s := range up.species {
		interactivity := "Habitat"
		switch s.Interactivity {
		case "full":
		case "exhibit":
			interactivity = "Exhibit"
		default:
			return "", fmt.Errorf("species %s: unknown interactivity %q", s.StringID, s.Interactivity)
		}
		domesticated, err := strconv.ParseBool(s.Domesticated)
		if err != nil {
			return "", fmt.Errorf("species %s: domesticated: %w", s.StringID, err)
		}
		fmt.Fprintf(&b, "{Key: %q, Label: %q, EngineToken: %q, Interactivity: %s, WaterNeeded: %t, FenceGrade: %d, Domesticated: %t},\n",
			s.StringID, s.Label, engineToken(s.StringID, s.Label), interactivity, s.WaterNeeded, s.FenceGrade, domesticated)
	}
	b.WriteString("}\n")
	return strings.ReplaceAll(b.String(), "gamedata.", ""), nil
}

func itemsTable(up upstream) (string, error) {
	speciesByLabel := make(map[string]string, len(up.species))
	for _, s := range up.species {
		speciesByLabel[s.Label] = s.StringID
	}
	var b bytes.Buffer
	b.WriteString("var Items = []Item{\n")
	for _, it := range up.items {
		if it.Version != "Base" {
			return "", fmt.Errorf("item %d: version %q: only the base game is modelled", it.ID, it.Version)
		}
		class, err := classification(it.APClassification)
		if err != nil {
			return "", fmt.Errorf("item %d: %w", it.ID, err)
		}
		eff, err := effect(it.Name, speciesByLabel, up.tokens)
		if err != nil {
			return "", fmt.Errorf("item %d: %w", it.ID, err)
		}
		fmt.Fprintf(&b, "{ID: %d, Name: %q, Classification: %s, Quantity: %d, Effect: %s},\n", it.ID, it.Name, class, it.Quantity, eff)
	}
	b.WriteString("}\n")
	return strings.ReplaceAll(b.String(), "gamedata.", ""), nil
}

var (
	welfareID   = regexp.MustCompile(`^(?:e_)?welfare(\d+)_`)
	guestsID    = regexp.MustCompile(`^guests_(\d+)$`)
	zooRatingID = regexp.MustCompile(`^zoo_rating(\d+)$`)
)

func locationsTable(up upstream) (string, error) {
	species := make(map[string]upstreamSpecies, len(up.species))
	for _, s := range up.species {
		species[s.StringID] = s
	}
	var b bytes.Buffer
	b.WriteString("var Locations = []Location{\n")
	for _, l := range up.locations {
		if err := agreesWithSpecies(l, species); err != nil {
			return "", fmt.Errorf("location %d (%s): %w", l.ID, l.StringID, err)
		}
		row, err := locationRow(l, up.tokens)
		if err != nil {
			return "", fmt.Errorf("location %d (%s): %w", l.ID, l.StringID, err)
		}
		b.WriteString(row + ",\n")
	}
	b.WriteString("}\n")
	return b.String(), nil
}

func locationRow(l upstreamLocation, tokens map[string]string) (string, error) {
	switch {
	case l.Type == "research welfare":
		m := welfareID.FindStringSubmatch(l.StringID)
		if m == nil {
			return "", fmt.Errorf("welfare location without a level")
		}
		return fmt.Sprintf("{ID: %d, Kind: WelfareResearch, Species: %q, Level: %s}", l.ID, l.SpeciesType, m[1]), nil
	case l.Type == "firsts" && strings.HasPrefix(l.StringID, "fa_"):
		return fmt.Sprintf("{ID: %d, Kind: FirstAcquisition, Species: %q}", l.ID, l.SpeciesType), nil
	case l.Type == "firsts" && strings.HasPrefix(l.StringID, "fb_"):
		return fmt.Sprintf("{ID: %d, Kind: FirstBreeding, Species: %q}", l.ID, l.SpeciesType), nil
	case l.Type == "conservation":
		return fmt.Sprintf("{ID: %d, Kind: ConservationRelease, Species: %q}", l.ID, l.SpeciesType), nil
	case l.Type == "milestones" && guestsID.MatchString(l.StringID):
		return fmt.Sprintf("{ID: %d, Kind: Milestone, Metric: GuestCount, Threshold: %s}", l.ID, guestsID.FindStringSubmatch(l.StringID)[1]), nil
	case l.Type == "milestones" && zooRatingID.MatchString(l.StringID):
		return fmt.Sprintf("{ID: %d, Kind: Milestone, Metric: ZooRating, Threshold: %s}", l.ID, zooRatingID.FindStringSubmatch(l.StringID)[1]), nil
	case l.Type == "mechanic":
		token, err := contentToken(l.Label, tokens)
		if err != nil {
			return "", err
		}
		return fmt.Sprintf("{ID: %d, Kind: MechanicResearch, Name: %q, Code: %q, ResearchKey: %q}", l.ID, l.Label, l.StringID, token), nil
	}
	return "", fmt.Errorf("unknown location type %q", l.Type)
}

func agreesWithSpecies(l upstreamLocation, species map[string]upstreamSpecies) error {
	s, ok := species[l.SpeciesType]
	if !ok {
		if l.SpeciesType != "none" || l.WaterNeeded || l.FenceGrade != 0 || l.Domesticated {
			return fmt.Errorf("species %q: not a species, and not a plain non-species location", l.SpeciesType)
		}
		return nil
	}
	if l.WaterNeeded != s.WaterNeeded || l.FenceGrade != s.FenceGrade || strconv.FormatBool(l.Domesticated) != s.Domesticated {
		return fmt.Errorf("disagrees with species %s on water, fence grade or domestication", s.StringID)
	}
	return nil
}
